"""CC0 original R3000A module with a relocatable data pointer."""
import struct


def original_irx():
    data=bytearray(0x200)
    data[:7]=b'\x7fELF\1\1\1'
    def half(at,value):struct.pack_into('<H',data,at,value)
    def word(at,value):struct.pack_into('<I',data,at,value)
    for at,value in ((0x10,0xff80),(0x12,8),(0x28,0x34),(0x2a,32),(0x2c,2),(0x2e,40),(0x30,1),(0x98,0x101)):
        half(at,value)
    for at,value in ((0x14,1),(0x1c,0x34),(0x20,0x180),(0x34,1),(0x38,0x100),
        (0x44,44),(0x48,60),(0x4c,7),(0x50,16),(0x54,0x70000080),(0x58,0x80),
        (0x64,39),(0x68,39),(0x6c,4),(0x70,4),(0x8c,40),(0x90,4),(0x94,16),
        (0x128,4),(0x140,40),(0x144,2),(0x184,9),(0x190,0x140),(0x194,8),(0x1a4,8)):
        word(at,value)
    data[0x9a:0xa7]=b'original-iop\0'
    code=[0x3c08001f,0xad040000,0x8caa0000,0,0x914b0000,0,0xad0b0004,0x24020000,0x03e00008,0]
    for index,value in enumerate(code):word(0x100+index*4,value)
    return bytes(data)
