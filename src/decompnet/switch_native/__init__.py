"""Switch CPU source development, separate from the five game-output backends."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

from .. import pc
from . import discovery, media, provider

ROOT = Path(__file__).parent
BACKEND_ID = 'switch-nxport-las-cpu-probe'


def revision():
    value = hashlib.sha256()
    for path in sorted(ROOT.rglob('*')):
        if path.is_file() and '__pycache__' not in path.parts:
            value.update(path.relative_to(ROOT).as_posix().encode() + b'\0' + path.read_bytes())
    value.update((ROOT.parent / 'nds_native/hash.hpp').read_bytes())
    return value.hexdigest()


def emit(binary, image_path, inspection, entries_path, game, report, *, name='guest', desktop=False, anchor_origins=()):
    text = inspection['segments'][0]
    command = [str(binary), str(image_path), str(inspection['base']),
               str(text['offset']), str(text['size']), str(entries_path), str(game), str(report), name]
    if anchor_origins:
        command.append('--anchor-origins')
    try:
        result = subprocess.run(command, input=''.join(f'{pc}\n' for pc in anchor_origins) if anchor_origins else None,
                                capture_output=True, text=True, encoding='utf-8', errors='replace', timeout=300)
    except (OSError, subprocess.TimeoutExpired) as error:
        raise pc.PCError('Switch source generation could not run: ' + str(error)) from error
    if result.returncode:
        raise pc.PCError('Switch source generation failed:\n' + result.stderr[-6000:])
    # Guard direct calls as well as calls routed through the native dispatcher.
    for source in game.glob(name + '_*.c'):
        body = source.read_text().replace('// Generated by nxport-lifter. Do not edit.',
            '// Generated by nxport-lifter; editable decomp.wtf CPU source.')
        guard_header = 'native_api.h' if desktop else 'code_guard.h'
        body = body.replace('#include "cpu.h"', '#include "cpu.h"\n#include "' + guard_header + '"')
        body = re.sub(r'(RT_FN void f_([0-9a-f]+)\(Cpu \*c\) \{)',
            lambda m: m[1] + ('\n    if (sw_function_enter(c, 0x' + m[2] + 'ull)) return;' if desktop else
                '\n    c->pc = 0x' + m[2] + 'ull; switch_code_guard(c);'), body)
        source.write_text(body, encoding='utf-8', newline='\n')


def generate(project, root):
    path = Path(project['input'])
    inspection = media.load(path, include_image=True)
    image = inspection.pop('image')
    binary = provider.build()
    game, runtime, assets = (root / name for name in ('game', 'runtime', 'assets'))
    for folder in (game, runtime, assets):
        folder.mkdir()
    (assets / 'image.bin').write_bytes(image)
    roots = discovery.entries(image, inspection)
    (root / 'entries.txt').write_text(''.join(str(entry) + '\n' for entry in roots))
    inspection['discovered_entries'] = roots
    text, data = inspection['segments'][0], inspection['segments'][2]
    emit(binary, assets / 'image.bin', inspection, root / 'entries.txt', game, root / 'translation.json')
    layout = dict(IMAGE_BASE=inspection['base'], IMAGE_ENTRY=inspection['entry'], IMAGE_SIZE=len(image),
                  TEXT_OFFSET=text['offset'], TEXT_SIZE=text['size'], DATA_OFFSET=data['offset'], DATA_SIZE=data['size'])
    header = '#pragma once\n'
    for name, value in layout.items():
        header += f'#define {name} {value}ull\n'
    header += '#define INPUT_SHA256 "' + inspection['input']['sha256'] + '"\n'
    header += '#define IMAGE_SHA256 "' + hashlib.sha256(image).hexdigest() + '"\n'
    (runtime / 'layout.h').write_text(header)
    for source, target in (('probe.c', runtime / 'probe.c'), ('integrity.cpp', runtime / 'integrity.cpp'),
            ('code_guard.h', runtime / 'code_guard.h'), ('Project.cmake', root / 'CMakeLists.txt'),
            ('README.project.md', root / 'README.md'), ('sources.json', root / 'sources.json')):
        shutil.copyfile(ROOT / source, target)
    shutil.copyfile(ROOT.parent / 'nds_native/hash.hpp', runtime / 'hash.hpp')
    for name in ('LICENSE', 'LICENSE-LASRecomp'):
        shutil.copyfile(ROOT / 'vendor/nxport-lifter' / name, root / (name + '.nxport.txt'))
    shutil.copyfile(ROOT / 'MIT.Kirikae.txt', root / 'MIT.Kirikae.txt')
    shutil.copyfile(ROOT / 'THIRD_PARTY.md', root / 'THIRD_PARTY.md')
    (root / 'analysis.json').write_text(json.dumps(inspection, indent=2) + '\n')
    with path.open('rb') as stream:
        if hashlib.file_digest(stream, 'sha256').hexdigest() != inspection['input']['sha256']:
            raise pc.PCError('Switch owner input changed during generation')
    manifest = dict(schema=pc.SCHEMA, platform='switch', output_kind='cpu-probe',
        backend=dict(id=BACKEND_ID, revision=revision()), execution_model='static-recompiled',
        runtime=dict(id='switch-bounded-cpu-harness', revision=revision()),
        inputs=[inspection['input']], build=dict(system='cmake', target='switch_probe'),
        files={p.relative_to(root).as_posix():hashlib.sha256(p.read_bytes()).hexdigest()
               for p in sorted(root.rglob('*')) if p.is_file()},
        fallback=dict(interpreter=False, runtime_compilation=False),
        qualification=dict(graphics=False, retail=False, kernel_services=False, audio=False, saves=False))
    (root / 'pc-project.json').write_text(json.dumps(manifest, indent=2) + '\n')


def export_probe(path, destination):
    # Validate before installing or compiling any tool, and before creating output.
    media.load(path)
    backend = pc.Backend(BACKEND_ID, 'switch', revision(), generate, experimental=True)
    return pc.export_backend(dict(platform='switch', input=str(Path(path).resolve())), destination, backend)
