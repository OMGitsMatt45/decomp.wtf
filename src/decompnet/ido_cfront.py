"""Run the original IDO 5.3 CC driver in a private working directory.

Classic CC accepts .C, and creates intermediate files and a template repository
in its current directory. This adapter preserves .cpp project sources, rebases
include paths, and isolates that per-compilation state. All compiler stages are
original IDO 5.3 programs; no target code is generated by this adapter.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

IRIX_INPUTS = {
    "usr/lib/CC": "abb6bbf2910785a0bd6d1b6198c47ad4d061d7e3713618c0aee20efc0d7a3c65",
    "usr/lib/c++/cfront": "9ebe0d0aa3827f8d671ac6fcee7bd1cc7698b8e35af2905e4b19e3baaec54651",
    "usr/lib/c++/ptcomp": "34c7db077e506cb1b84152c2eba665bfe631368c59440816202101bfcedc55a3",
    "usr/lib/c++/markc++": "1616be281460d1be1cdb2f1f0821a90610ad7cf4ee186753fa938cc5374afe7e",
    "usr/lib/c++/ptlink": "7b00bdda3ab68240335ca8eb5c0955a73961dd370378ea0e434b93ecfead880e",
}


def manifest_error(root: Path) -> str | None:
    try:
        manifest = json.loads((root / "cfront-build.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return "The IDO 5.3 classic cfront build manifest is missing or invalid; reinstall ido-5.3 with --force --accept-license."
    if not isinstance(manifest, dict) or manifest.get("format") != 1 \
            or manifest.get("frontend") != "cfront" or manifest.get("toolchain") != "ido-5.3" \
            or manifest.get("upstream_revision") != "d5aec59932034b8a20f23f471297a55c45dcbc45" \
            or manifest.get("irix_inputs") != IRIX_INPUTS:
        return "The classic cfront overlay does not identify the pinned original IDO 5.3 inputs; reinstall ido-5.3 with --force --accept-license."
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--driver", required=True, type=Path)
    parser.add_argument("--src", required=True, type=Path)
    parser.add_argument("--obj", required=True, type=Path)
    parser.add_argument("--include", required=True, type=Path)
    args, flags = parser.parse_known_args(argv)
    if flags[:1] == ["--"]:
        flags = flags[1:]
    driver, source, output, include = (p.resolve() for p in (args.driver, args.src, args.obj, args.include))
    root = Path.cwd()
    # A relative input/output keeps legacy driver string handling independent
    # of spaces in the application or exported project directory.
    with tempfile.TemporaryDirectory(prefix=".ido-cfront-", dir=root) as temporary:
        work = Path(temporary)
        shutil.copyfile(source, work / "func.C")
        rebased = []
        index = 0
        while index < len(flags):
            flag = flags[index]
            if flag == "-I" and index + 1 < len(flags):
                index += 1
                rebased += ["-I" + os.path.relpath(root / flags[index], work)]
            elif flag.startswith("-I") and len(flag) > 2:
                rebased += ["-I" + os.path.relpath(root / flag[2:], work)]
            else:
                rebased.append(flag)
            index += 1
        command = [str(driver), "-c", *rebased,
                   "-I" + os.path.relpath(include, work), "-I" + os.path.relpath(source.parent, work),
                   "func.C", "-o", "func.o"]
        try:
            result = subprocess.run(command, cwd=work)
        except OSError as error:
            parser.exit(1, f"couldn't start IDO 5.3 classic CC: {error}\n")
        if result.returncode:
            return result.returncode
        obj = work / "func.o"
        if not obj.is_file():
            parser.exit(1, "IDO 5.3 classic CC returned success without producing an object\n")
        output.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(obj, output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
